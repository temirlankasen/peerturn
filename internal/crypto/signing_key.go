package crypto

import "crypto/ed25519"

// ValidSigningKey rejects noncanonical field encodings and every small-order
// Ed25519 public key. Signature verification remains with crypto/ed25519.
func ValidSigningKey(raw []byte) bool {
	if len(raw) != ed25519.PublicKeySize {
		return false
	}
	var y [32]byte
	copy(y[:], raw)
	y[31] &= 0x7f
	// RFC8032 section 5.1.3 requires y < p = 2^255-19. The sign bit
	// encodes x and must not participate in the field-element comparison.
	canonical := false
	for i := 31; i >= 0; i-- {
		limit := byte(0xff)
		switch i {
		case 31:
			limit = 0x7f
		case 0:
			limit = 0xed
		}
		if y[i] < limit {
			canonical = true
			break
		}
		if y[i] > limit {
			return false
		}
	}
	if !canonical {
		return false
	}
	// These five y coordinates cover all eight torsion points after removing
	// the x sign: two order-4, identity, order-2, and four order-8 encodings.
	// Folding the sign also rejects negative-zero aliases of x=0.
	for _, smallOrder := range smallOrderY {
		if y == smallOrder {
			return false
		}
	}
	return true
}

// Public torsion coordinates also listed by libsodium 1.0.18's
// ge25519_has_small_order; no curve arithmetic is reproduced here.
var smallOrderY = [5][32]byte{
	{},
	{1},
	{0x26, 0xe8, 0x95, 0x8f, 0xc2, 0xb2, 0x27, 0xb0, 0x45, 0xc3, 0xf4, 0x89, 0xf2, 0xef, 0x98, 0xf0,
		0xd5, 0xdf, 0xac, 0x05, 0xd3, 0xc6, 0x33, 0x39, 0xb1, 0x38, 0x02, 0x88, 0x6d, 0x53, 0xfc, 0x05},
	{0xc7, 0x17, 0x6a, 0x70, 0x3d, 0x4d, 0xd8, 0x4f, 0xba, 0x3c, 0x0b, 0x76, 0x0d, 0x10, 0x67, 0x0f,
		0x2a, 0x20, 0x53, 0xfa, 0x2c, 0x39, 0xcc, 0xc6, 0x4e, 0xc7, 0xfd, 0x77, 0x92, 0xac, 0x03, 0x7a},
	{0xec, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
		0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
}
